#!/usr/bin/env python3
"""Freeze the exact observed M1 decision/quote-anchor schedule used by training.

This records the resolver's observed NY-labeled bars and their next-market-bar
quote anchors. It does not assert that every elapsed minute was expected to
trade, identify the CFD provider calendar, or establish that an interval is a
missing bar. Existing tick-coverage evidence is checked for schedule-count
parity but is not regenerated by this script.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from quant_rl.config import load_config  # noqa: E402
from quant_rl.data.split import get_split_config, make_train_mask  # noqa: E402
from quant_rl.train.train_rl import _tick_execution_split_schedule  # noqa: E402


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def timestamp_fingerprint(values: pd.DatetimeIndex) -> dict[str, Any]:
    # Normalize timezone-aware bars to UTC nanoseconds before hashing.
    canonical = np.asarray(values, dtype="datetime64[ns]").view("<i8")
    return {
        "count": len(values),
        "first": str(values[0]) if len(values) else None,
        "last": str(values[-1]) if len(values) else None,
        "sha256_utc_ns_little_endian": hashlib.sha256(canonical.tobytes()).hexdigest(),
    }


def position_fingerprint(values: np.ndarray[Any, Any]) -> str:
    canonical = np.asarray(values, dtype="<i8")
    return hashlib.sha256(canonical.tobytes()).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument(
        "--coverage-report",
        type=Path,
        default=Path("docs/thesis/evidence/replacement_data_20261017/tick_execution_coverage.json"),
    )
    parser.add_argument(
        "--schedule-shape-report",
        type=Path,
        default=Path(
            "docs/thesis/evidence/replacement_data_20261017/replacement_schedule_shape.json"
        ),
    )
    args = parser.parse_args()

    output = args.out if args.out.is_absolute() else ROOT / args.out
    output = output.resolve()
    output.relative_to(ROOT)
    if output.exists():
        raise FileExistsError(f"refusing to overwrite schedule fingerprint: {output}")

    def repo_path(path: Path) -> Path:
        resolved = path if path.is_absolute() else ROOT / path
        resolved = resolved.resolve()
        resolved.relative_to(ROOT)
        if not resolved.is_file():
            raise FileNotFoundError(resolved)
        return resolved

    coverage_path = repo_path(args.coverage_report)
    shape_path = repo_path(args.schedule_shape_report)
    coverage_report = json.loads(coverage_path.read_text(encoding="utf-8"))
    shape_report = json.loads(shape_path.read_text(encoding="utf-8"))
    cfg = load_config()
    train_end, test_start = get_split_config(cfg)
    config_path = ROOT / "quant_rl/config/default.yaml"
    schedule_rows: dict[str, Any] = {}
    source_rows: dict[str, Any] = {}

    for symbol in [str(value) for value in cfg.data.symbols]:
        cache_path = ROOT / str(cfg.data.cache_dir) / f"{symbol}_M1_v2-full-day.parquet"
        source_path = ROOT / str(cfg.data.raw_dir) / str(cfg.data.m1_files[symbol])
        cache_path = cache_path.resolve()
        source_path = source_path.resolve()
        cache_path.relative_to(ROOT)
        source_path.relative_to(ROOT)
        frame = pd.read_parquet(cache_path)
        index = pd.DatetimeIndex(frame.index)
        source_sha256 = sha256_file(source_path)
        cache_sha256 = sha256_file(cache_path)
        prior_symbol_report = coverage_report["symbols"][symbol]
        if source_sha256 != prior_symbol_report["m1_source"]["sha256"]:
            raise ValueError(f"{symbol} M1 source hash changed after coverage audit")
        if cache_sha256 != prior_symbol_report["m1_cache"]["sha256"]:
            raise ValueError(f"{symbol} M1 cache hash changed after coverage audit")
        session_labels = frame["session"]
        schedule = _tick_execution_split_schedule(
            index,
            make_train_mask(index, train_end),
            test_start,
            session_labels=session_labels,
        )
        symbol_coverage = prior_symbol_report["training_tick_cache_coverage"]
        split_rows: dict[str, Any] = {}
        for split, values in schedule.items():
            count = len(values["decision_times"])
            coverage_count = int(symbol_coverage[split]["order_count"])
            if count != coverage_count:
                raise ValueError(
                    f"{symbol} {split} schedule has {count} decisions but coverage report has "
                    f"{coverage_count}"
                )
            split_rows[split] = {
                "decision_timestamps": timestamp_fingerprint(values["decision_times"]),
                "decision_positions_sha256_int64_le": position_fingerprint(
                    values["decision_positions"]
                ),
                "next_market_quote_anchor_timestamps": timestamp_fingerprint(
                    values["quote_anchor_times"]
                ),
                "quote_anchor_positions_sha256_int64_le": position_fingerprint(
                    values["quote_anchor_positions"]
                ),
                "tick_coverage_report_order_count": coverage_count,
                "tick_coverage_count_parity": True,
            }
        schedule_rows[symbol] = split_rows
        source_rows[symbol] = {
            "m1_source": {
                "path": str(source_path),
                "bytes": source_path.stat().st_size,
                "sha256": sha256_file(source_path),
            },
            "m1_cache": {
                "path": str(cache_path),
                "bytes": cache_path.stat().st_size,
                "sha256": sha256_file(cache_path),
                "rows": len(frame),
                "first_observed_bar": str(index[0]),
                "last_observed_bar": str(index[-1]),
                "source_cache_exact_match_in_coverage_report": bool(
                    prior_symbol_report["m1_cache"]["source_cache_exact_match"]
                ),
            },
        }

    if coverage_report["config_sha256"] != sha256_file(config_path):
        raise ValueError("tick-coverage report config hash differs from current config")
    if not all(
        row["m1_cache"]["source_cache_exact_match"] for row in coverage_report["symbols"].values()
    ):
        raise ValueError("tick-coverage report does not establish M1 source/cache parity")

    source_files = [
        ROOT / "scripts/research/fingerprint_tick_decision_schedule.py",
        ROOT / "quant_rl/train/train_rl.py",
        ROOT / "quant_rl/data/split.py",
        ROOT / "quant_rl/data/session.py",
        config_path,
        coverage_path,
        shape_path,
    ]
    result = {
        "schema_version": 1,
        "created_at": datetime.now().astimezone().isoformat(),
        "repository_head": subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
        ).strip(),
        "working_tree_status": subprocess.check_output(
            ["git", "status", "--porcelain"], cwd=ROOT, text=True
        ).splitlines(),
        "host": platform.node(),
        "architecture": platform.machine(),
        "slurm_job_id": os.environ.get("SLURM_JOB_ID"),
        "config": {
            "path": str(config_path.relative_to(ROOT)),
            "sha256": sha256_file(config_path),
            "train_end_inclusive": train_end,
            "test_start_inclusive": test_start,
            "timezone": str(cfg.data.tz),
            "session_window_start": str(cfg.session.start),
            "session_window_end": str(cfg.session.end),
        },
        "schedule_semantics": {
            "eligibility": "Observed M1 rows labeled NY in the versioned cache; no regular time grid is synthesized.",
            "training_selection": "make_train_mask through the configured inclusive train_end, AND NY session label.",
            "testing_selection": "Observed M1 timestamps at or after configured test_start, AND NY session label.",
            "quote_anchor": "The next row in the complete observed M1 index, including a non-NY row when it follows the final eligible NY row; final index row clamps to itself, matching the trainer preflight.",
            "interval_interpretation": "Counts and gaps describe observed bars only. The shorter Dec 2/4 schedules may reflect holidays or provider-specific reduced hours; the available evidence cannot identify the CFD provider calendar or distinguish scheduled closure from export omission. No expected-minute grid or missing-bar claim is made, and no bars are imputed.",
        },
        "symbols": schedule_rows,
        "inputs": source_rows,
        "cross_references": {
            "tick_coverage_report": {
                "path": str(coverage_path.relative_to(ROOT)),
                "sha256": sha256_file(coverage_path),
                "purpose": "Existing exact cache parity and randomized tick-coverage evidence; schedule counts are cross-checked here.",
                "coverage_recomputed_by_this_script": False,
            },
            "observed_schedule_shape_report": {
                "path": str(shape_path.relative_to(ROOT)),
                "sha256": sha256_file(shape_path),
                "gap_semantics": {
                    symbol: shape_report[symbol]["gap_semantics"] for symbol in schedule_rows
                },
            },
        },
        "source_sha256": {str(path.relative_to(ROOT)): sha256_file(path) for path in source_files},
        "limitations": [
            "This fingerprints an input schedule; it is not a model, backtest, campaign, or strategy result.",
            "A timestamp fingerprint proves exact reproducibility of the observed schedule but does not prove market-data source identity, feed-use/publication rights, provider trading hours, or an untouched holdout.",
            "Tick quote coverage remains the separately cited report's result; it is not recomputed here.",
            "The old 18-variant campaign remains inadmissible and no readiness gate is changed by this artifact.",
        ],
    }

    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_name(f".{output.name}.{os.getpid()}.tmp")
    try:
        temporary.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        temporary.replace(output)
    finally:
        temporary.unlink(missing_ok=True)
    print(
        json.dumps(
            {
                "output": str(output),
                "counts": {
                    symbol: {
                        split: details["decision_timestamps"]["count"]
                        for split, details in rows.items()
                    }
                    for symbol, rows in schedule_rows.items()
                },
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
